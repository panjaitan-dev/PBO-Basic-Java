/* W01 - Struktur program Java.
   KAPAN: setiap program. Nama file harus sama dengan nama class public. */
public class S01_StrukturProgram {            // class = wadah kode
    public static void main(String[] args) { // titik masuk program
        System.out.println("Halo PBO!");     // println = cetak + baris baru
        System.out.print("Tanpa baris baru "); // print = tanpa baris baru
        System.out.println();
        System.out.printf("Format: %d, %.2f, %s%n", 5, 3.14159, "teks"); // printf = format
    }
}
